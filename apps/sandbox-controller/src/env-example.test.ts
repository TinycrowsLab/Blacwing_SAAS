// The repository `.env.example` must boot the controller config on the fixed dev port, bound to loopback.
import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { loadSandboxControllerConfig } from './config.js';

function exampleEnv(): Record<string, string> {
  const out: Record<string, string> = {};
  const text = readFileSync(new URL('../../../.env.example', import.meta.url), 'utf8');
  for (const line of text.split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line);
    if (match?.[1] !== undefined) out[match[1]] = match[2] ?? '';
  }
  return out;
}

describe('.env.example vs the sandbox controller config', () => {
  it('leaves the token secret empty (generated by dev:deps) and boots once it is filled', () => {
    const example = exampleEnv();
    expect(example.SBX_RUN_TOKEN_SECRET).toBe('');
    const config = loadSandboxControllerConfig({
      ...example,
      NODE_ENV: 'test',
      // `${KEY}` references are expanded by dev:deps; stand in for the expanded values here.
      VALKEY_URL: 'redis://:pw@127.0.0.1:16379/0',
      SBX_RUN_TOKEN_SECRET: 'f'.repeat(48),
    });
    expect(config.SBX_MGMT_ADDR).toEqual({ host: '127.0.0.1', port: 13_700 });
    expect(config.SBX_DRIVER).toBe('docker');
  });
});
