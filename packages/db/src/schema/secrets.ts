import { sql } from 'drizzle-orm';
import {
  check,
  foreignKey,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  EXTERNAL_SECRET_BACKENDS,
  SECRET_BACKENDS,
  SECRET_NAME_MAX,
  SECRET_STATUSES,
  SECRET_TYPES,
} from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Secret records (SECRETS-003, F35, CONTEXT_PACK §7, §8.6, §8.7). A `secrets` row is the metadata and
 * the encrypted envelope (or the locator of an external store) of one credential; every other table
 * points at it with an opaque `secret_ref` URI (`@blackwing/contracts`) and never stores a value.
 * Consumers must resolve a ref through the Secrets Service (SECRETS-006), never read these tables, so
 * external-backend secrets behave the same way. Writes and resolution are SECRETS-004/006.
 *
 * `envelope` is the SECRETS-002 ciphertext envelope and `external_locator` the BYOK pointer
 * (ARN, vault path, key URL). Neither ever holds plaintext: the check constraints below reject a
 * plaintext-looking key as a guard against a careless writer, not as proof; the real guarantee is
 * that the only writer encrypts first. The forward-only migration in `migrations/` is generated from
 * this file (`pnpm db:generate`) and then reviewed; FORCE ROW LEVEL SECURITY, the grants and the
 * `updated_at` trigger are appended by hand because Drizzle does not model them.
 */

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** Keys that would mean a writer put a value, not ciphertext, into a JSON column. */
const PLAINTEXT_KEYS = "array['plaintext', 'secret', 'password']";

/** Name of the unique index behind `(tenant_id, name)`. */
export const SECRETS_NAME_INDEX = 'secrets_tenant_name_idx';

export const secrets = pgTable(
  'secrets',
  {
    /** UUIDv7 generated by the writer; the `secretId` of a `secret_ref`. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    /** NFC-normalised, no control characters (`secretNameSchema`); enforced again below. */
    name: text('name').notNull(),
    type: text('type', { enum: SECRET_TYPES }),
    purpose: text('purpose'),
    backend: text('backend', { enum: SECRET_BACKENDS }).notNull().default('openbao'),
    /** SECRETS-002 envelope of the current version; null when the value lives in an external store, or once shredded. */
    envelope: jsonb('envelope').$type<Record<string, unknown>>(),
    /** Where an external (BYOK) backend keeps the value; required for those backends. */
    externalLocator: jsonb('external_locator').$type<Record<string, unknown>>(),
    currentVersion: integer('current_version').notNull().default(1),
    status: text('status', { enum: SECRET_STATUSES }).notNull().default('active'),
    ...timestamps(),
  },
  (t) => [
    // Also the target of secret_versions' composite FK, so a version can never name another tenant's secret.
    uniqueIndex('secrets_tenant_id_id_idx').on(t.tenantId, t.id),
    uniqueIndex(SECRETS_NAME_INDEX).on(t.tenantId, t.name),
    check(
      'secrets_name_check',
      sql`length(${t.name}) BETWEEN 1 AND ${sql.raw(String(SECRET_NAME_MAX))} AND ${t.name} IS NFC NORMALIZED AND ${t.name} !~ '[[:cntrl:]]'`,
    ),
    check('secrets_type_check', sql`${t.type} IS NULL OR ${t.type} IN (${inList(SECRET_TYPES)})`),
    check('secrets_backend_check', sql`${t.backend} IN (${inList(SECRET_BACKENDS)})`),
    check('secrets_status_check', sql`${t.status} IN (${inList(SECRET_STATUSES)})`),
    check('secrets_current_version_check', sql`${t.currentVersion} >= 1`),
    check(
      'secrets_envelope_object_check',
      sql`${t.envelope} IS NULL OR jsonb_typeof(${t.envelope}) = 'object'`,
    ),
    check(
      'secrets_locator_object_check',
      sql`${t.externalLocator} IS NULL OR jsonb_typeof(${t.externalLocator}) = 'object'`,
    ),
    // An external backend keeps the value elsewhere, so without a locator the record points at nothing.
    check(
      'secrets_external_locator_check',
      sql`${t.backend} NOT IN (${inList(EXTERNAL_SECRET_BACKENDS)}) OR ${t.externalLocator} IS NOT NULL`,
    ),
    // Every live secret has a value somewhere; only a shredded one may have neither.
    check(
      'secrets_has_value_check',
      sql`${t.status} = 'shredded' OR ${t.envelope} IS NOT NULL OR ${t.externalLocator} IS NOT NULL`,
    ),
    // §8.7 guard: no plaintext-looking key at the top level of either JSON column.
    check(
      'secrets_no_plaintext_check',
      sql`NOT (coalesce(${t.envelope}, '{}'::jsonb) ?| ${sql.raw(PLAINTEXT_KEYS)}) AND NOT (coalesce(${t.externalLocator}, '{}'::jsonb) ?| ${sql.raw(PLAINTEXT_KEYS)})`,
    ),
    // The canonical tenant policy (`rlsPolicySql` shape): no TO clause, access is granted to bw_app only.
    pgPolicy('secrets_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** Rotation history (SECRETS-012): one row per version of a secret, so a pinned `?v=` ref keeps resolving. */
export const secretVersions = pgTable(
  'secret_versions',
  {
    /** Denormalised from the secret so the row carries its own RLS anchor; the FK keeps it equal. */
    tenantId: uuid('tenant_id').notNull(),
    secretId: uuid('secret_id').notNull(),
    version: integer('version').notNull(),
    envelope: jsonb('envelope').$type<Record<string, unknown>>(),
    externalLocator: jsonb('external_locator').$type<Record<string, unknown>>(),
    createdAt: ts('created_at').notNull().defaultNow(),
    /** Set when a newer version supersedes this one and the grace period ends. */
    retiredAt: ts('retired_at'),
  },
  (t) => [
    primaryKey({ columns: [t.secretId, t.version] }),
    foreignKey({
      name: 'secret_versions_secret_fk',
      columns: [t.tenantId, t.secretId],
      foreignColumns: [secrets.tenantId, secrets.id],
    }),
    index('secret_versions_tenant_id_idx').on(t.tenantId),
    check('secret_versions_version_check', sql`${t.version} >= 1`),
    check(
      'secret_versions_envelope_object_check',
      sql`${t.envelope} IS NULL OR jsonb_typeof(${t.envelope}) = 'object'`,
    ),
    check(
      'secret_versions_locator_object_check',
      sql`${t.externalLocator} IS NULL OR jsonb_typeof(${t.externalLocator}) = 'object'`,
    ),
    check(
      'secret_versions_retired_check',
      sql`${t.retiredAt} IS NULL OR ${t.retiredAt} >= ${t.createdAt}`,
    ),
    check(
      'secret_versions_no_plaintext_check',
      sql`NOT (coalesce(${t.envelope}, '{}'::jsonb) ?| ${sql.raw(PLAINTEXT_KEYS)}) AND NOT (coalesce(${t.externalLocator}, '{}'::jsonb) ?| ${sql.raw(PLAINTEXT_KEYS)})`,
    ),
    pgPolicy('secret_versions_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type SecretRow = typeof secrets.$inferSelect;
export type NewSecretRow = typeof secrets.$inferInsert;
export type SecretVersionRow = typeof secretVersions.$inferSelect;
export type NewSecretVersionRow = typeof secretVersions.$inferInsert;
