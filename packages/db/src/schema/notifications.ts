import { sql } from 'drizzle-orm';
import {
  check,
  index,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  NOTIFICATION_CHANNEL_KINDS,
  NOTIFICATION_CHANNEL_NAME_MAX,
  NOTIFICATION_CHANNEL_STATUSES,
} from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Notification channels (NOTIFY-001, CONTEXT_PACK §7, §8.6, §8.7). `config` holds only non-secret settings,
 * and every credential sits in the secrets service: `secret_ref` is the opaque `bw-secret://` URI of that
 * record and is never the value. The check constraints below are guards against a careless writer; the
 * real guarantee is that the API validates the config strictly (`@blackwing/contracts`) and seals the
 * secret before it reaches this table. A channel is never deleted (history and audit survive); it is
 * disabled. The forward-only migration is generated from this file (`pnpm db:generate`), and the FORCE RLS,
 * grants and `updated_at` trigger are appended by hand.
 */

/** Name of the unique index behind `(tenant_id, name)`; the writer maps its violation to `CHANNEL_NAME_CONFLICT`. */
export const NOTIFICATION_CHANNELS_NAME_INDEX = 'notification_channels_tenant_name_idx';

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** Keys that would mean a writer put a credential, not a setting, into `config`. */
const CREDENTIAL_KEYS =
  "array['secret', 'token', 'password', 'api_key', 'apikey', 'routing_key', 'webhook_url', 'hmac_key']";

export const notificationChannels = pgTable(
  'notification_channels',
  {
    /** UUIDv7 generated by the writer. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    kind: text('kind', { enum: NOTIFICATION_CHANNEL_KINDS }).notNull(),
    /** NFC-normalised, no control characters (`notificationChannelNameSchema`); unique per tenant. */
    name: text('name').notNull(),
    /** Non-secret settings only (addresses, public URL, region). Validated strictly per kind before the write. */
    config: jsonb('config')
      .$type<Record<string, unknown>>()
      .notNull()
      .default(sql`'{}'::jsonb`),
    /** `bw-secret://{tenantId}/{secretId}` of the credential (NOTIFY-001 §8.7); null for kinds with no credential. */
    secretRef: text('secret_ref'),
    status: text('status', { enum: NOTIFICATION_CHANNEL_STATUSES }).notNull().default('active'),
    createdBy: uuid('created_by').notNull(),
    ...timestamps(),
  },
  (t) => [
    uniqueIndex(NOTIFICATION_CHANNELS_NAME_INDEX).on(t.tenantId, t.name),
    index('notification_channels_tenant_id_idx').on(t.tenantId),
    check(
      'notification_channels_name_check',
      sql`length(${t.name}) BETWEEN 1 AND ${sql.raw(String(NOTIFICATION_CHANNEL_NAME_MAX))} AND ${t.name} IS NFC NORMALIZED AND ${t.name} !~ '[[:cntrl:]]' AND btrim(${t.name}) <> ''`,
    ),
    check(
      'notification_channels_kind_check',
      sql`${t.kind} IN (${inList(NOTIFICATION_CHANNEL_KINDS)})`,
    ),
    check(
      'notification_channels_status_check',
      sql`${t.status} IN (${inList(NOTIFICATION_CHANNEL_STATUSES)})`,
    ),
    check('notification_channels_config_object_check', sql`jsonb_typeof(${t.config}) = 'object'`),
    // §8.7 guard: no credential-looking key in the plaintext settings.
    check(
      'notification_channels_no_credential_check',
      sql`NOT (${t.config} ?| ${sql.raw(CREDENTIAL_KEYS)})`,
    ),
    // A ref names this tenant's secret: a ref pointing into another tenant's prefix is refused.
    check(
      'notification_channels_secret_ref_check',
      sql`${t.secretRef} IS NULL OR starts_with(${t.secretRef}, 'bw-secret://' || ${t.tenantId}::text || '/')`,
    ),
    // Kinds that deliver with a credential must carry a ref; email must not.
    check(
      'notification_channels_secret_presence_check',
      sql`(${t.kind} = 'email') = (${t.secretRef} IS NULL)`,
    ),
    pgPolicy('notification_channels_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type NotificationChannelRow = typeof notificationChannels.$inferSelect;
export type NewNotificationChannelRow = typeof notificationChannels.$inferInsert;
