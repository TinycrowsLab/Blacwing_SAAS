import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  pgPolicy,
  pgTable,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { GATE_DECISIONS, GATE_SUBJECT_TYPES } from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Gate decisions (AUTHZ, CONTEXT_PACK §7, §8.4, §8.8). Gate 1, Gate 2, Gate 3 and the SA approval share this table.
 * Rows are append-only: the runtime role gets SELECT and INSERT only, so a decision is never edited or removed and
 * the audit trail survives. Separation of duties is enforced in service code (`@blackwing/domain`, RBAC-011), by the
 * unique partial index below (no second `approved` row per subject), and by the generated DB trigger that AUTHZ-009
 * adds. The forward-only migration in `migrations/` is generated from this file (`pnpm db:generate`); the FORCE RLS
 * and grants are appended by hand because Drizzle does not model them.
 */

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
const inList = (values: readonly string[]) =>
  sql.raw(values.map((value) => `'${value}'`).join(', '));

export const authzGateDecisions = pgTable(
  'authz_gate_decisions',
  {
    /** UUIDv7 generated by the writer. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    /** Gate 1, 2 or 3 (checked). */
    gate: smallint('gate').notNull(),
    subjectType: text('subject_type', { enum: GATE_SUBJECT_TYPES }).notNull(),
    subjectId: uuid('subject_id').notNull(),
    decision: text('decision', { enum: GATE_DECISIONS }).notNull(),
    /** The deciding user. Null only for an automatic decision (`auto`). */
    actorId: uuid('actor_id'),
    reason: text('reason'),
    decidedAt: ts('decided_at'),
    timeoutAt: ts('timeout_at'),
    auto: boolean('auto').notNull().default(false),
    ...timestamps(),
  },
  (t) => [
    index('authz_gate_decisions_tenant_subject_idx').on(t.tenantId, t.subjectType, t.subjectId),
    index('authz_gate_decisions_gate_idx').on(t.gate),
    // Race-safety backstop: at most one `approved` decision per gate and subject in a tenant.
    uniqueIndex('authz_gate_decisions_one_approved_idx')
      .on(t.tenantId, t.gate, t.subjectId)
      .where(sql`${t.decision} = 'approved'`),
    check('authz_gate_decisions_gate_check', sql`${t.gate} IN (1, 2, 3)`),
    check(
      'authz_gate_decisions_subject_type_check',
      sql`${t.subjectType} IN (${inList(GATE_SUBJECT_TYPES)})`,
    ),
    check('authz_gate_decisions_decision_check', sql`${t.decision} IN (${inList(GATE_DECISIONS)})`),
    // The canonical tenant policy (`rlsPolicySql` shape): fail-closed predicate, no `missing_ok`.
    pgPolicy('authz_gate_decisions_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type AuthzGateDecisionRow = typeof authzGateDecisions.$inferSelect;
export type NewAuthzGateDecisionRow = typeof authzGateDecisions.$inferInsert;
