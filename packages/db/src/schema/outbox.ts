import { sql } from 'drizzle-orm';
import {
  check,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  OUTBOX_DEDUPE_KEY_MAX,
  OUTBOX_MESSAGE_TYPES,
  OUTBOX_PAYLOAD_MAX_BYTES,
  OUTBOX_STATUSES,
  type OutboxPayload,
} from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Transactional outbox (WORKFLOW-001 follow-up, F12, F34, CONTEXT_PACK §7, §8.6, §8.8). A domain write
 * and its side-effect intents (audit events, notifications, workflow signals) commit in one
 * transaction as rows here, so delivery is at least once with no dual-write race. `withOutbox`
 * (`../outbox.ts`) is the only writer; the relay that dispatches rows is WORKFLOW-012. The
 * forward-only migration in `migrations/` is generated from this file (`pnpm db:generate`) and then
 * reviewed; FORCE ROW LEVEL SECURITY, the grants and the `updated_at` trigger are
 * appended by hand because Drizzle does not model them.
 *
 * Every instant is the database clock (`now()`): `available_at` has no application-side source.
 */

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** Name of the partial unique index behind the per-tenant idempotency key. */
export const OUTBOX_DEDUPE_INDEX = 'outbox_tenant_dedupe_key_idx';

export const outbox = pgTable(
  'outbox',
  {
    /** UUIDv7 generated by the writer, so ids sort by creation time. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    aggregateType: text('aggregate_type'),
    aggregateId: uuid('aggregate_id'),
    type: text('type', { enum: OUTBOX_MESSAGE_TYPES }).notNull(),
    /** References only, never secret values (§8.7); at most 64 KiB, larger bodies are stored as a pointer. */
    payload: jsonb('payload').$type<OutboxPayload>().notNull(),
    dedupeKey: text('dedupe_key'),
    status: text('status', { enum: OUTBOX_STATUSES }).notNull().default('pending'),
    attempts: integer('attempts').notNull().default(0),
    availableAt: ts('available_at').notNull().defaultNow(),
    dispatchedAt: ts('dispatched_at'),
    lastError: text('last_error'),
    ...timestamps(),
  },
  (t) => [
    // The relay's claim query: `status = 'pending' AND available_at <= now() ORDER BY available_at`.
    index('outbox_status_available_at_idx').on(t.status, t.availableAt),
    // Idempotency: one message per (tenant, key). Rows without a key never collide. The tenant is the
    // leading column, so this also serves tenant-scoped lookups.
    uniqueIndex(OUTBOX_DEDUPE_INDEX)
      .on(t.tenantId, t.dedupeKey)
      .where(sql`${t.dedupeKey} IS NOT NULL`),
    check('outbox_type_check', sql`${t.type} IN (${inList(OUTBOX_MESSAGE_TYPES)})`),
    check('outbox_status_check', sql`${t.status} IN (${inList(OUTBOX_STATUSES)})`),
    check('outbox_payload_object_check', sql`jsonb_typeof(${t.payload}) = 'object'`),
    check(
      'outbox_payload_size_check',
      sql`octet_length(${t.payload}::text) <= ${sql.raw(String(OUTBOX_PAYLOAD_MAX_BYTES))}`,
    ),
    check(
      'outbox_dedupe_key_check',
      sql`${t.dedupeKey} IS NULL OR length(${t.dedupeKey}) BETWEEN 1 AND ${sql.raw(String(OUTBOX_DEDUPE_KEY_MAX))}`,
    ),
    check('outbox_attempts_check', sql`${t.attempts} >= 0`),
    check(
      'outbox_dispatched_check',
      sql`${t.status} <> 'dispatched' OR ${t.dispatchedAt} IS NOT NULL`,
    ),
    // The canonical tenant policy (`rlsPolicySql` shape): no TO clause, access is granted to bw_app only.
    pgPolicy('outbox_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type OutboxRow = typeof outbox.$inferSelect;
export type NewOutboxRow = typeof outbox.$inferInsert;
