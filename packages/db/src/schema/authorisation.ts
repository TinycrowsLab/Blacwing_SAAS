import { sql } from 'drizzle-orm';
import {
  check,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  type IntrusivenessClass,
  SA_STATUSES,
  SELECTABLE_INTRUSIVENESS_CLASSES,
} from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Standing authorisations (AUTHZ-001, CONTEXT_PACK §7, §8.1, §8.3, §8.6). An SA is the customer's signed,
 * expiring permission to test a set of assets; no target traffic happens without a valid, unexpired,
 * signature-verified envelope derived from it (§8.1). This table is the data foundation; the lifecycle is
 * `packages/domain` (`authorisation/state.ts`) and canonicalisation, signing and the API are later issues.
 *
 * `max_intrusiveness` is limited to the selectable classes, so `destructive` is never a valid ceiling
 * (§8.3). `valid_from < expires_at` and a non-empty `asset_ids` are enforced here too, not only by the
 * creation validator. Rows are never hard-deleted: an SA ends as `expired` or `revoked`, so the audit
 * trail survives (the grants in the migration revoke DELETE). The forward-only migration in `migrations/`
 * is generated from this file (`pnpm db:generate`), then the RLS block (`rlsPolicySql`) and the
 * `updated_at` trigger are appended by hand because Drizzle does not model FORCE RLS or grants.
 */

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** Name of the unique index behind `(tenant_id, public_id)`-style lookups of an SA by its public id. */
export const SA_PUBLIC_ID_KEY = 'standing_authorisations_public_id_key';

export const standingAuthorisations = pgTable(
  'standing_authorisations',
  {
    /** UUIDv7 generated by the writer; the uuid behind the `sa_…` public id. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    /** Prefixed public id (`sa_…`), a re-encoding of `id`; unique. */
    publicId: text('public_id').notNull(),
    /** The assets this SA covers. Never empty (see `standing_authorisations_asset_ids_check`). */
    assetIds: uuid('asset_ids').array().notNull(),
    /** Include/exclude hosts, paths, ports and methods (SCOPE-002). Validated by the scope module. */
    scopeRules: jsonb('scope_rules').$type<Record<string, unknown>>().notNull(),
    /** Highest intrusiveness class the SA allows. Never `destructive` (§8.3). */
    maxIntrusiveness: text('max_intrusiveness').$type<IntrusivenessClass>().notNull(),
    preApprovedTestClasses: text('pre_approved_test_classes')
      .array()
      .notNull()
      .default(sql`'{}'::text[]`),
    /** Request budgets the SA grants by default (SCOPE-004). */
    defaultBudgets: jsonb('default_budgets').$type<Record<string, unknown>>().notNull(),
    /** Allowed test windows: an array of `{ cron, tz }` with an IANA timezone, never a fixed offset. */
    testWindows: jsonb('test_windows').$type<Record<string, unknown>[]>().notNull(),
    validFrom: ts('valid_from').notNull(),
    expiresAt: ts('expires_at').notNull(),
    requesterId: uuid('requester_id').notNull(),
    /** Set on approval; `approver_id <> requester_id` is enforced by the approval step (AUTHZ-009). */
    approverId: uuid('approver_id'),
    /** JWS over the canonical body; populated by the signing step (AUTHZ-004). No secret is stored here. */
    signature: text('signature'),
    signingKeyId: text('signing_key_id'),
    /** Optimistic concurrency: a losing writer reloads and retries. */
    version: integer('version').notNull().default(1),
    status: text('status', { enum: SA_STATUSES }).notNull().default('draft'),
    revocationReason: text('revocation_reason'),
    ...timestamps(),
  },
  (t) => [
    unique(SA_PUBLIC_ID_KEY).on(t.publicId),
    index('standing_authorisations_tenant_id_idx').on(t.tenantId),
    index('standing_authorisations_status_idx').on(t.status),
    index('standing_authorisations_expires_at_idx').on(t.expiresAt),
    index('standing_authorisations_asset_ids_gin_idx').using('gin', t.assetIds),
    check('standing_authorisations_status_check', sql`${t.status} IN (${inList(SA_STATUSES)})`),
    check(
      'standing_authorisations_max_intrusiveness_check',
      sql`${t.maxIntrusiveness} IN (${inList(SELECTABLE_INTRUSIVENESS_CLASSES)})`,
    ),
    check('standing_authorisations_window_check', sql`${t.validFrom} < ${t.expiresAt}`),
    check('standing_authorisations_asset_ids_check', sql`cardinality(${t.assetIds}) >= 1`),
    check('standing_authorisations_version_check', sql`${t.version} >= 1`),
    check(
      'standing_authorisations_scope_rules_object_check',
      sql`jsonb_typeof(${t.scopeRules}) = 'object'`,
    ),
    check(
      'standing_authorisations_default_budgets_object_check',
      sql`jsonb_typeof(${t.defaultBudgets}) = 'object'`,
    ),
    check(
      'standing_authorisations_test_windows_array_check',
      sql`jsonb_typeof(${t.testWindows}) = 'array'`,
    ),
    // The canonical tenant policy (`rlsPolicySql` shape): fail-closed predicate, no `missing_ok`.
    pgPolicy('standing_authorisations_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type StandingAuthorisationRow = typeof standingAuthorisations.$inferSelect;
export type NewStandingAuthorisationRow = typeof standingAuthorisations.$inferInsert;
