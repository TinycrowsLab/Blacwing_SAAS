import { sql } from 'drizzle-orm';
import {
  check,
  foreignKey,
  index,
  jsonb,
  pgPolicy,
  pgTable,
  type PgTableExtraConfigValue,
  text,
  unique,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { ASSESSMENT_REQUEST_STATUSES, RUN_MODES, RUN_TRIGGERS } from '@blackwing/contracts';

import { idColumn, stateVersion, tenantIdColumn, tenantIdIndex, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Assessment requests and their input manifests (SCOPE-001, CONTEXT_PACK §7, §8.3, §8.6, §8.7). An
 * `assessment_requests` row is the scoping form's output; the `runs` table (ORCH) is created from an approved
 * one. An `input_manifests` row lists what the customer supplied for it. Credentials are references only.
 *
 * Both tables are tenant tables: they carry the §7 policy from `TENANT_PREDICATE`. The migration is generated
 * from this file (`pnpm db:generate`) and then reviewed. FORCE ROW LEVEL SECURITY, the grants and the
 * `updated_at` trigger are appended by hand because Drizzle does not model them.
 *
 * `asset_ids` is a uuid array, which Postgres cannot reference with a foreign key; asset membership is
 * checked by the service layer (SCOPE-005). `sa_id` and `requested_by` are plain uuids until their owning
 * tables (AUTHZ / standing authorisations) exist.
 */

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/**
 * Intrusiveness a request may authorise. `destructive` is never a member (§8.3). Mirrors
 * `authorisableIntrusivenessSchema`; `scope.test.ts` fails if the two drift apart.
 */
export const MAX_INTRUSIVENESS = ['passive', 'active_safe', 'state_changing'] as const;

/** A request that has left `draft` must name its standing authorisation and at least one asset. */
const SUBMITTED_OR_LATER = ['submitted', 'promoted', 'rejected'] as const;

export const assessmentRequests = pgTable(
  'assessment_requests',
  {
    /** UUIDv7 generated by the writer. */
    id: idColumn(),
    tenantId: tenantIdColumn(),
    /** The `areq_…` public id of `id` (`publicId('areq', id)`). */
    publicId: text('public_id').notNull(),
    mode: text('mode', { enum: RUN_MODES }).notNull(),
    /** Free text, length-capped by the API schema (`LIMITS.objectiveMax`), stored as UTF-8. */
    objective: text('objective').notNull(),
    /** Assets under test. Non-empty once submitted (CHECK below and the service rule, SCOPE-005). */
    assetIds: uuid('asset_ids').array().notNull(),
    /** The standing authorisation, nullable in a draft and required once submitted. */
    saId: uuid('sa_id'),
    inputManifestId: uuid('input_manifest_id'),
    /** Ordered include/exclude rules (`scopeRulesSchema`); the default is an empty object, a draft-only value. */
    scopeRules: jsonb('scope_rules').$type<Record<string, unknown>>().notNull().default({}),
    maxIntrusiveness: text('max_intrusiveness', { enum: MAX_INTRUSIVENESS }).notNull(),
    /** Run budgets (`runBudgetsSchema`), validated before they are stored. */
    budgets: jsonb('budgets').$type<Record<string, unknown>>().notNull(),
    trigger: text('trigger', { enum: RUN_TRIGGERS }).notNull(),
    status: text('status', { enum: ASSESSMENT_REQUEST_STATUSES }).notNull().default('draft'),
    requestedBy: uuid('requested_by').notNull(),
    ...timestamps(),
    ...stateVersion(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('assessment_requests', t.tenantId),
    uniqueIndex('assessment_requests_public_id_key').on(t.publicId),
    index('assessment_requests_status_idx').on(t.status),
    index('assessment_requests_asset_ids_idx').using('gin', t.assetIds),
    index('assessment_requests_input_manifest_id_idx').on(t.inputManifestId),
    // Target of the input manifest's composite FK, so a manifest can never name another tenant's request.
    unique('assessment_requests_tenant_id_id_unique').on(t.tenantId, t.id),
    // Composite FK: plain FK checks bypass RLS, so a single-column reference could cross tenants.
    foreignKey({
      name: 'assessment_requests_input_manifest_fk',
      columns: [t.tenantId, t.inputManifestId],
      foreignColumns: [inputManifests.tenantId, inputManifests.id],
    }),
    check(
      'assessment_requests_public_id_check',
      sql`starts_with(${t.publicId}, 'areq_') AND length(${t.publicId}) > 5`,
    ),
    check('assessment_requests_mode_check', sql`${t.mode} IN (${inList(RUN_MODES)})`),
    check('assessment_requests_objective_check', sql`length(${t.objective}) >= 1`),
    check(
      'assessment_requests_max_intrusiveness_check',
      sql`${t.maxIntrusiveness} <> 'destructive' AND ${t.maxIntrusiveness} IN (${inList(MAX_INTRUSIVENESS)})`,
    ),
    check('assessment_requests_budgets_object_check', sql`jsonb_typeof(${t.budgets}) = 'object'`),
    check(
      'assessment_requests_scope_rules_object_check',
      sql`jsonb_typeof(${t.scopeRules}) = 'object'`,
    ),
    check('assessment_requests_trigger_check', sql`${t.trigger} IN (${inList(RUN_TRIGGERS)})`),
    check(
      'assessment_requests_status_check',
      sql`${t.status} IN (${inList(ASSESSMENT_REQUEST_STATUSES)})`,
    ),
    // A submitted (or later) request has its standing authorisation and at least one asset.
    check(
      'assessment_requests_submitted_check',
      sql`${t.status} NOT IN (${inList(SUBMITTED_OR_LATER)}) OR (${t.saId} IS NOT NULL AND cardinality(${t.assetIds}) >= 1)`,
    ),
    pgPolicy('assessment_requests_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** The input manifest of an assessment request: what the customer supplied, by reference (SCOPE-001). */
export const inputManifests = pgTable(
  'input_manifests',
  {
    id: idColumn(),
    tenantId: tenantIdColumn(),
    /** Nullable: a manifest outlives its request (`ON DELETE SET NULL`, see the migration), so evidence is kept. */
    assessmentRequestId: uuid('assessment_request_id'),
    /** URLs and CIDRs in scope for supply, as `{kind, value}` objects. */
    suppliedTargets: jsonb('supplied_targets').$type<unknown[]>().notNull().default([]),
    /** Per-role credential references (`{role, secretRef}`). Never a plaintext secret (§8.7). */
    credentialRefs: jsonb('credential_refs').$type<unknown[]>().notNull().default([]),
    /** Uploaded spec objects (`{kind, objectKey, sha256, sizeBytes, status}`). */
    specObjects: jsonb('spec_objects').$type<unknown[]>().notNull().default([]),
    /** Source repository reference (`{url?, ref?, deployKeyRef?, archiveKey?}`), or null. */
    sourceRepo: jsonb('source_repo').$type<Record<string, unknown>>(),
    configManifestObjects: jsonb('config_manifest_objects')
      .$type<unknown[]>()
      .notNull()
      .default([]),
    roleMatrixId: uuid('role_matrix_id'),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('input_manifests', t.tenantId),
    unique('input_manifests_tenant_id_id_unique').on(t.tenantId, t.id),
    index('input_manifests_assessment_request_id_idx').on(t.assessmentRequestId),
    // Composite, with the FK column list narrowed to `assessment_request_id` (the migration hand-edits the
    // ON DELETE clause, since `tenant_id` is NOT NULL): a deleted request leaves its manifest unlinked.
    foreignKey({
      name: 'input_manifests_assessment_request_fk',
      columns: [t.tenantId, t.assessmentRequestId],
      foreignColumns: [assessmentRequests.tenantId, assessmentRequests.id],
    }).onDelete('set null'),
    check(
      'input_manifests_supplied_targets_array_check',
      sql`jsonb_typeof(${t.suppliedTargets}) = 'array'`,
    ),
    check(
      'input_manifests_credential_refs_array_check',
      sql`jsonb_typeof(${t.credentialRefs}) = 'array'`,
    ),
    check(
      'input_manifests_spec_objects_array_check',
      sql`jsonb_typeof(${t.specObjects}) = 'array'`,
    ),
    check(
      'input_manifests_config_objects_array_check',
      sql`jsonb_typeof(${t.configManifestObjects}) = 'array'`,
    ),
    check(
      'input_manifests_source_repo_object_check',
      sql`${t.sourceRepo} IS NULL OR jsonb_typeof(${t.sourceRepo}) = 'object'`,
    ),
    pgPolicy('input_manifests_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);
