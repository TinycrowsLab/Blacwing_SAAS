/**
 * The asset inventory (ASSET-001, CONTEXT_PACK §7, §8.6, §8.7, §8.10): `assets`, `asset_credentials`,
 * `role_matrices`, `asset_tags`, `asset_groups` and the `asset_group_members` join. Every table is a tenant
 * table with the §7 policy from `TENANT_PREDICATE`, so a missing tenant context reads zero rows. The migration
 * is generated from this file (`pnpm db:generate`) and reviewed. FORCE ROW LEVEL SECURITY, the grants and the
 * `updated_at` triggers are appended by hand because Drizzle does not model them.
 *
 * Enums are `text` with a CHECK list typed from the contract tuples, never native pg enums, so a value added
 * later is one forward-only migration. Child rows reference their asset with a composite `(tenant_id, asset_id)`
 * foreign key: plain foreign keys bypass RLS, so a single-column reference could cross tenants. Credentials are
 * OpenBao references only (`secret_ref`); no plaintext column exists (§8.7).
 */

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** The 64 KiB cap of the jsonb columns, as a SQL literal (ASSET_JSON_MAX_BYTES is a compile-time constant). */
const JSON_MAX_BYTES = sql.raw(String(ASSET_JSON_MAX_BYTES));

/** Prefix of every credential secret reference (§8.7). Mirrors the seed's `openbao://` references. */
export const SECRET_REF_PREFIX = 'openbao://';

export const assets = pgTable(
  'assets',
  {
    /** UUIDv7 generated by the writer; `publicId` is the `asset_…` form of it. */
    id: idColumn(),
    tenantId: tenantIdColumn(),
    /** The `asset_…` public id of `id` (`publicId('asset', id)`). */
    publicId: text('public_id').notNull(),
    type: text('type', { enum: ASSET_TYPES }).notNull(),
    name: text('name').notNull(),
    /** Normalised identifiers (`assetIdentifiersSchema`): at least one, at most 64 KiB, never plaintext secrets. */
    identifiers: jsonb('identifiers').$type<AssetIdentifier[]>().notNull(),
    environment: text('environment', { enum: ASSET_ENVIRONMENTS }).notNull(),
    ownerUserId: uuid('owner_user_id')
      .notNull()
      .references(() => users.id),
    verificationStatus: text('verification_status', { enum: VERIFICATION_STATUSES })
      .notNull()
      .default('unverified'),
    verificationMethod: text('verification_method', { enum: VERIFICATION_METHODS }),
    verifiedAt: timestamp('verified_at', { withTimezone: true, mode: 'date' }),
    verificationExpiresAt: timestamp('verification_expires_at', {
      withTimezone: true,
      mode: 'date',
    }),
    /** The F6 environment attestation (`assetAttestationSchema`), written by ASSET-004. */
    attestation: jsonb('attestation').$type<Record<string, unknown>>(),
    /** Optimistic concurrency for the REST API (`ETag` / `If-Match`, ASSET-002). Bumped by every write. */
    ...stateVersion(),
    /** `Idempotency-Key` of the create that made this row, and the digest of that request's body (ASSET-002). */
    idempotencyKey: text('idempotency_key'),
    idempotencyFingerprint: text('idempotency_fingerprint'),
    ...softDelete(),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('assets', t.tenantId),
    unique('assets_public_id_key').on(t.publicId),
    // Target of the child tables' composite foreign keys.
    unique('assets_tenant_id_id_unique').on(t.tenantId, t.id),
    index('assets_owner_user_id_idx').on(t.ownerUserId),
    index('assets_type_idx').on(t.type),
    index('assets_verification_status_idx').on(t.verificationStatus),
    index('assets_identifiers_gin_idx').using('gin', t.identifiers),
    // A replayed create with the same `Idempotency-Key` resolves to the row it made (per tenant).
    uniqueIndex('assets_tenant_idempotency_key_idx')
      .on(t.tenantId, t.idempotencyKey)
      .where(sql`${t.idempotencyKey} IS NOT NULL`),
    // Lookups and lists read live assets only; soft-deleted rows stay out of the index.
    index('assets_live_tenant_type_idx')
      .on(t.tenantId, t.type)
      .where(sql`${t.deletedAt} IS NULL`),
    check('assets_state_version_check', sql`${t.stateVersion} >= 0`),
    check(
      'assets_idempotency_check',
      sql`(${t.idempotencyKey} IS NULL) = (${t.idempotencyFingerprint} IS NULL)`,
    ),
    check(
      'assets_public_id_check',
      sql`starts_with(${t.publicId}, 'asset_') AND length(${t.publicId}) > 6`,
    ),
    check(
      'assets_name_check',
      sql`length(${t.name}) BETWEEN 1 AND ${sql.raw(String(LIMITS.labelMax))}`,
    ),
    check('assets_type_check', sql`${t.type} IN (${inList(ASSET_TYPES)})`),
    check('assets_environment_check', sql`${t.environment} IN (${inList(ASSET_ENVIRONMENTS)})`),
    check(
      'assets_verification_status_check',
      sql`${t.verificationStatus} IN (${inList(VERIFICATION_STATUSES)})`,
    ),
    check(
      'assets_verification_method_check',
      sql`${t.verificationMethod} IS NULL OR ${t.verificationMethod} IN (${inList(VERIFICATION_METHODS)})`,
    ),
    // CASE, not AND: PostgreSQL does not short-circuit, and jsonb_array_length errors on a non-array.
    check(
      'assets_identifiers_array_check',
      sql`CASE WHEN jsonb_typeof(${t.identifiers}) = 'array' THEN jsonb_array_length(${t.identifiers}) >= 1 ELSE false END`,
    ),
    check(
      'assets_identifiers_size_check',
      sql`octet_length(${t.identifiers}::text) <= ${JSON_MAX_BYTES}`,
    ),
    check(
      'assets_attestation_check',
      sql`${t.attestation} IS NULL OR (jsonb_typeof(${t.attestation}) = 'object' AND octet_length(${t.attestation}::text) <= ${JSON_MAX_BYTES})`,
    ),
    // Only a verified asset may be targeted (§8.10), and it must record how and when it was verified.
    check(
      'assets_verified_evidence_check',
      sql`${t.verificationStatus} <> 'verified' OR (${t.verificationMethod} IS NOT NULL AND ${t.verifiedAt} IS NOT NULL)`,
    ),
    pgPolicy('assets_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** The per-role login of an asset (§7 `asset_credentials`). The secret itself lives in OpenBao. */
export const assetCredentials = pgTable(
  'asset_credentials',
  {
    id: idColumn(),
    tenantId: tenantIdColumn(),
    assetId: uuid('asset_id').notNull(),
    roleName: text('role_name').notNull(),
    /** An OpenBao reference (`openbao://…`). Never a plaintext credential (§8.7). */
    secretRef: text('secret_ref').notNull(),
    /** How to log in as this role (steps, selectors). Contains no secret values. */
    loginRecipe: jsonb('login_recipe').$type<Record<string, unknown>>().notNull(),
    mfaType: text('mfa_type', { enum: MFA_TYPES }).notNull(),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('asset_credentials', t.tenantId),
    unique('asset_credentials_asset_id_role_name_key').on(t.assetId, t.roleName),
    foreignKey({
      name: 'asset_credentials_asset_fk',
      columns: [t.tenantId, t.assetId],
      foreignColumns: [assets.tenantId, assets.id],
    }),
    check(
      'asset_credentials_role_name_check',
      sql`length(${t.roleName}) BETWEEN 1 AND ${sql.raw(String(LIMITS.shortTextMax))}`,
    ),
    check(
      'asset_credentials_secret_ref_check',
      sql`starts_with(${t.secretRef}, '${sql.raw(SECRET_REF_PREFIX)}') AND length(${t.secretRef}) <= ${sql.raw(String(LIMITS.urlMax))}`,
    ),
    check(
      'asset_credentials_login_recipe_check',
      sql`jsonb_typeof(${t.loginRecipe}) = 'object' AND octet_length(${t.loginRecipe}::text) <= ${JSON_MAX_BYTES}`,
    ),
    check('asset_credentials_mfa_type_check', sql`${t.mfaType} IN (${inList(MFA_TYPES)})`),
    pgPolicy('asset_credentials_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** A versioned role-by-function access matrix of an asset (F9). At most one version is active per asset. */
export const roleMatrices = pgTable(
  'role_matrices',
  {
    id: idColumn(),
    tenantId: tenantIdColumn(),
    assetId: uuid('asset_id').notNull(),
    version: integer('version').notNull(),
    /** roles × functions → `allow | deny | conditional`. */
    matrix: jsonb('matrix').$type<Record<string, unknown>>().notNull(),
    active: boolean('active').notNull().default(false),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('role_matrices', t.tenantId),
    unique('role_matrices_asset_id_version_key').on(t.assetId, t.version),
    uniqueIndex('role_matrices_one_active_per_asset_key')
      .on(t.assetId)
      .where(sql`${t.active}`),
    foreignKey({
      name: 'role_matrices_asset_fk',
      columns: [t.tenantId, t.assetId],
      foreignColumns: [assets.tenantId, assets.id],
    }),
    check('role_matrices_version_check', sql`${t.version} >= 1`),
    check(
      'role_matrices_matrix_check',
      sql`jsonb_typeof(${t.matrix}) = 'object' AND octet_length(${t.matrix}::text) <= ${JSON_MAX_BYTES}`,
    ),
    pgPolicy('role_matrices_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** A key/value label on an asset (§7 `asset_tags`). The key is unique per asset. */
export const assetTags = pgTable(
  'asset_tags',
  {
    tenantId: tenantIdColumn(),
    assetId: uuid('asset_id').notNull(),
    key: text('key').notNull(),
    value: text('value').notNull(),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('asset_tags', t.tenantId),
    primaryKey({ name: 'asset_tags_pkey', columns: [t.tenantId, t.assetId, t.key] }),
    foreignKey({
      name: 'asset_tags_asset_fk',
      columns: [t.tenantId, t.assetId],
      foreignColumns: [assets.tenantId, assets.id],
    }),
    check(
      'asset_tags_key_check',
      sql`length(${t.key}) BETWEEN 1 AND ${sql.raw(String(LIMITS.keyMax))}`,
    ),
    check('asset_tags_value_check', sql`length(${t.value}) <= ${sql.raw(String(LIMITS.labelMax))}`),
    pgPolicy('asset_tags_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

