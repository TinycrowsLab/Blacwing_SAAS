/** Membership of an asset in a group (§7 `asset_group_members`). Both sides are composite, tenant-keyed FKs. */
export const assetGroupMembers = pgTable(
  'asset_group_members',
  {
    tenantId: tenantIdColumn(),
    groupId: uuid('group_id').notNull(),
    assetId: uuid('asset_id').notNull(),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('asset_group_members', t.tenantId),
    primaryKey({
      name: 'asset_group_members_pkey',
      columns: [t.tenantId, t.groupId, t.assetId],
    }),
    index('asset_group_members_asset_id_idx').on(t.assetId),
    foreignKey({
      name: 'asset_group_members_group_fk',
      columns: [t.tenantId, t.groupId],
      foreignColumns: [assetGroups.tenantId, assetGroups.id],
    }),
    foreignKey({
      name: 'asset_group_members_asset_fk',
      columns: [t.tenantId, t.assetId],
      foreignColumns: [assets.tenantId, assets.id],
    }),
    pgPolicy('asset_group_members_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

