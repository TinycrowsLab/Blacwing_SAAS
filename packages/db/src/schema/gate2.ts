import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  GATE2_IDEMPOTENCY_KEY_MAX,
  GATE2_STATES,
  INTRUSIVENESS_CLASSES,
  type Gate2ProposedAction,
} from '@blackwing/contracts';

import { idColumn, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Gate 2 runtime exceptions and the gate decision ledger (GATE2-001, F13, F31, CONTEXT_PACK §3.2
 * step 8, §7, §8.2-§8.4, §8.8). The forward-only migration in `migrations/` is generated from this
 * file (`pnpm db:generate`) and then reviewed; FORCE ROW LEVEL SECURITY, the grants, the guard
 * triggers and the `updated_at` trigger are appended by hand because Drizzle does not model them.
 *
 * WRITES GO THROUGH `createGate2Exception` / `decideGate2Exception` (`../gate2.ts`). The database
 * enforces the invariants regardless of the caller:
 * - a row is born `pending`; the only legal change is `pending -> approved_once | denied | timed_out
 *   | superseded` with `state_version` + 1, and a decided row never changes again;
 * - `approved_once` needs a `decided_by` that is neither `requester_id` nor `plan_approver_id`
 *   (§8.4), an intrusiveness other than `destructive` (§8.3) and a `decided_at` before `timeout_at`
 *   (silence is a denial, §8.2);
 * - every terminal transition has exactly one matching `gate_decisions` row by commit time.
 */

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly (string | number)[]) {
  return sql.raw(
    values.map((value) => (typeof value === 'number' ? value : `'${value}'`)).join(', '),
  );
}

/** Name of the unique constraint behind the per-tenant idempotency key. */
export const GATE2_IDEMPOTENCY_CONSTRAINT = 'gate2_exceptions_tenant_idempotency_key';

export const gate2Exceptions = pgTable(
  'gate2_exceptions',
  {
    /** UUIDv7 generated by the writer, so ids sort by creation time. */
    id: idColumn(),
    tenantId: uuid('tenant_id').notNull(),
    runId: uuid('run_id').notNull(),
    sessionId: text('session_id').notNull(),
    subtaskId: uuid('subtask_id'),
    testCaseId: uuid('test_case_id'),
    toolName: text('tool_name').notNull(),
    /** Redacted summary of the deferred call (§8.7): references, never secret values. */
    proposedAction: jsonb('proposed_action').$type<Gate2ProposedAction>().notNull(),
    /** Why the PDP denied or deferred (the Cedar diagnostic). */
    envelopeReason: text('envelope_reason').notNull(),
    intrusiveness: text('intrusiveness', { enum: INTRUSIVENESS_CLASSES }).notNull(),
    batch: boolean('batch').notNull().default(false),
    state: text('state', { enum: GATE2_STATES }).notNull().default('pending'),
    /** Optimistic concurrency token: every accepted transition adds 1. */
    stateVersion: integer('state_version').notNull().default(0),
    requesterId: uuid('requester_id'),
    planApproverId: uuid('plan_approver_id'),
    /** The person who approved or denied; NULL while pending and for a timeout or supersede. */
    decidedBy: uuid('decided_by'),
    decidedAt: ts('decided_at'),
    /** When silence becomes a denial (F13). */
    timeoutAt: ts('timeout_at').notNull(),
    idempotencyKey: text('idempotency_key').notNull(),
    ...timestamps(),
  },
  (t) => [
    unique(GATE2_IDEMPOTENCY_CONSTRAINT).on(t.tenantId, t.idempotencyKey),
    index('gate2_exceptions_tenant_run_state_idx').on(t.tenantId, t.runId, t.state),
    check('gate2_exceptions_state_check', sql`${t.state} IN (${inList(GATE2_STATES)})`),
    check(
      'gate2_exceptions_intrusiveness_check',
      sql`${t.intrusiveness} IN (${inList(INTRUSIVENESS_CLASSES)})`,
    ),
    check('gate2_exceptions_state_version_check', sql`${t.stateVersion} >= 0`),
    check('gate2_exceptions_tool_name_check', sql`length(btrim(${t.toolName})) > 0`),
    check('gate2_exceptions_envelope_reason_check', sql`length(btrim(${t.envelopeReason})) > 0`),
    check('gate2_exceptions_session_id_check', sql`length(btrim(${t.sessionId})) > 0`),
    check(
      'gate2_exceptions_idempotency_key_check',
      sql`length(${t.idempotencyKey}) BETWEEN 1 AND ${sql.raw(String(GATE2_IDEMPOTENCY_KEY_MAX))}`,
    ),
    check(
      'gate2_exceptions_proposed_action_check',
      sql`jsonb_typeof(${t.proposedAction}) = 'object'`,
    ),
    check('gate2_exceptions_timeout_check', sql`${t.timeoutAt} > ${t.createdAt}`),
    // Pending <=> undecided; the two human states carry the person, the system states do not.
    check(
      'gate2_exceptions_decided_at_check',
      sql`(${t.state} = 'pending') = (${t.decidedAt} IS NULL)`,
    ),
    check(
      'gate2_exceptions_decided_by_check',
      sql`(${t.state} IN ('approved_once', 'denied')) = (${t.decidedBy} IS NOT NULL)`,
    ),
    // Separation of duties (§8.4): the approver is neither the requester nor the plan approver.
    check(
      'gate2_exceptions_sod_check',
      sql`${t.state} <> 'approved_once' OR (${t.decidedBy} IS DISTINCT FROM ${t.requesterId} AND ${t.decidedBy} IS DISTINCT FROM ${t.planApproverId})`,
    ),
    // No destructive approval, ever (§8.3).
    check(
      'gate2_exceptions_no_destructive_approval_check',
      sql`NOT (${t.state} = 'approved_once' AND ${t.intrusiveness} = 'destructive')`,
    ),
    // A late approval is a denial (F13): the decision instant is before the timeout.
    check(
      'gate2_exceptions_approved_in_time_check',
      sql`${t.state} <> 'approved_once' OR ${t.decidedAt} < ${t.timeoutAt}`,
    ),
    pgPolicy('gate2_exceptions_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

export type Gate2ExceptionRow = typeof gate2Exceptions.$inferSelect;
export type NewGate2ExceptionRow = typeof gate2Exceptions.$inferInsert;
