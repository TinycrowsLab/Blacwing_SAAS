import { sql } from 'drizzle-orm';
import {
  check,
  foreignKey,
  index,
  jsonb,
  numeric,
  pgPolicy,
  boolean,
  pgTable,
  type PgTableExtraConfigValue,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  type BaselineStatus,
  baselineStatusSchema,
  type EvidenceChainRef,
  type FindingStatus,
  findingStatusSchema,
} from '@blackwing/contracts';

import { idColumn, stateVersion, tenantIdColumn, tenantIdIndex, timestamps } from '../columns.js';
import { TENANT_PREDICATE } from './columns.js';

/**
 * Findings and their per-run occurrences (FINDING-001, CONTEXT_PACK §3.4, §7, §8.6). A finding is the
 * canonical record every downstream module reads and writes: validation, triage, baseline and report.
 * A `finding_occurrences` row records that a run saw it again.
 *
 * Both are tenant tables: they carry the §7 policy from `TENANT_PREDICATE`. The migration is generated from
 * this file (`pnpm db:generate --name findings_schema`) and then reviewed. FORCE ROW LEVEL SECURITY, the
 * grants and the `updated_at` trigger are appended by hand because Drizzle does not model them.
 *
 * `asset_id`, `run_id`, `first_seen_run_id` and `last_seen_run_id` are plain uuids until the `assets` (ASSET)
 * and `runs` (ORCH) tables exist: a foreign key to a table that is not there cannot be written. The same
 * rule as `assessment_requests` applies. The composite `(tenant_id, finding_id)` key of occurrences is real.
 */

/** Byte caps on the jsonb columns (FINDING-001 edge cases): large context belongs in an evidence reference. */
export const FINDING_LOCATION_MAX_BYTES = 8192;
export const FINDING_SEVERITY_MAX_BYTES = 4096;
export const FINDING_CLASSIFICATION_MAX_BYTES = 4096;
/** Length cap on each reporter narrative column (`LIMITS.reasonMax`, in characters). */
const FINDING_NARRATIVE_MAX_CHARS = 2000;

/** SQL `IN (...)` list from a constant tuple (values are compile-time constants, never input). */
function inList(values: readonly string[]) {
  return sql.raw(values.map((value) => `'${value}'`).join(', '));
}

/** Enum tuples for the column types (zod exposes the options as a plain array). */
const FINDING_STATUSES = findingStatusSchema.options as [FindingStatus, ...FindingStatus[]];
const BASELINE_STATUSES = baselineStatusSchema.options as [BaselineStatus, ...BaselineStatus[]];

/** Statuses a finding only reaches after a human released it (Gate 3). Mirrors `RELEASED_FINDING_STATUSES`. */
const RELEASED_STATUSES = ['released', 'fixed', 'returned'] as const;

export const findings = pgTable(
  'findings',
  {
    /** UUIDv7 generated by the writer. */
    id: idColumn(),
    tenantId: tenantIdColumn(),
    /** The `fnd_…` public id of `id` (`publicId('fnd', id)`). */
    publicId: text('public_id').notNull(),
    /** Dedup key within a tenant: lower-case SHA-256 hex (FINDING-003 computes it). */
    fingerprint: text('fingerprint').notNull(),
    /** NFC-normalised label, length-capped by the contract (`labelSchema`). */
    title: text('title').notNull(),
    class: text('class').notNull(),
    cweId: text('cwe_id'),
    owaspCategory: text('owasp_category'),
    /** Version of the curated mapping that classified the finding (`mappingVersionSchema`), §8.9. */
    mappingVersion: text('mapping_version'),
    /** True when there is no primary CWE or no OWASP category: the finding awaits analyst review (FINDING-004). */
    unmapped: boolean('unmapped').notNull().default(false),
    /** Candidate CWEs, API Top 10 and WSTG refs the classifier kept (`findingClassificationSchema`). */
    classification: jsonb('classification').$type<Record<string, unknown>>(),
    /** CVSS vectors and score (`severitySchema`); null until the validator scores the finding (FINDING-005). */
    severity: jsonb('severity').$type<Record<string, unknown>>(),
    assetId: uuid('asset_id').notNull(),
    /** Structured location (`findingLocationSchema`): method, URL template, parameter, file and line. */
    location: jsonb('location').$type<Record<string, unknown>>().notNull(),
    status: text('status', { enum: FINDING_STATUSES }).notNull(),
    baselineStatus: text('baseline_status', { enum: BASELINE_STATUSES }),
    runId: uuid('run_id').notNull(),
    firstSeenRunId: uuid('first_seen_run_id').notNull(),
    lastSeenRunId: uuid('last_seen_run_id').notNull(),
    /** Validator confidence in [0, 1] (FINDING-007). */
    confidence: numeric('confidence', { precision: 4, scale: 3, mode: 'number' }),
    /** Reason and expiry of an `accepted_risk` triage decision (`acceptedRiskSchema`). Set exactly for that status. */
    acceptedRisk: jsonb('accepted_risk').$type<Record<string, unknown>>(),
    releasedBy: uuid('released_by'),
    releasedAt: timestamp('released_at', { withTimezone: true, mode: 'date' }),
    /**
     * The reporter's write-up (REGISTRY-021 `finding-report.v1`, REPORT-001). Each is null until the write-up exists;
     * the report model carries it as data and never renders it as code. Prose only: no payloads, no walkthroughs.
     */
    description: text('description'),
    impact: text('impact'),
    evidenceNarrative: text('evidence_narrative'),
    severityRationale: text('severity_rationale'),
    remediationSummary: text('remediation_summary'),
    /** ASVS v5.0.0 requirement ids the reporter cites, e.g. `ASVS v5.0.0-4.2.1`. Null until the write-up exists. */
    asvsRefs: jsonb('asvs_refs').$type<string[]>(),
    ...timestamps(),
    ...stateVersion(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('findings', t.tenantId),
    uniqueIndex('findings_public_id_key').on(t.publicId),
    // Dedup backbone (FINDING-003): one finding per fingerprint within a tenant.
    uniqueIndex('findings_tenant_id_fingerprint_key').on(t.tenantId, t.fingerprint),
    index('findings_tenant_id_status_idx').on(t.tenantId, t.status),
    // Target of the occurrences' composite FK, so an occurrence can never name another tenant's finding.
    unique('findings_tenant_id_id_unique').on(t.tenantId, t.id),
    check(
      'findings_public_id_check',
      sql`starts_with(${t.publicId}, 'fnd_') AND length(${t.publicId}) > 4`,
    ),
    check('findings_fingerprint_check', sql`${t.fingerprint} ~ '^[0-9a-f]{64}$'`),
    check(
      'findings_mapping_version_check',
      sql`${t.mappingVersion} IS NULL OR ${t.mappingVersion} ~ '^[0-9]+\\.[0-9]+\\.[0-9]+$'`,
    ),
    // A mapped finding names its primary CWE and OWASP category; only an unmapped one may lack them.
    check(
      'findings_mapped_check',
      sql`${t.unmapped} OR (${t.cweId} IS NOT NULL AND ${t.owaspCategory} IS NOT NULL)`,
    ),
    check(
      'findings_classification_check',
      sql`${t.classification} IS NULL OR (jsonb_typeof(${t.classification}) = 'object' AND octet_length(${t.classification}::text) <= ${sql.raw(String(FINDING_CLASSIFICATION_MAX_BYTES))})`,
    ),
    check('findings_title_check', sql`length(${t.title}) BETWEEN 1 AND 200`),
    check('findings_class_check', sql`length(${t.class}) BETWEEN 1 AND 120`),
    check('findings_cwe_id_check', sql`${t.cweId} IS NULL OR ${t.cweId} ~ '^CWE-[1-9][0-9]{0,4}$'`),
    check(
      'findings_owasp_category_check',
      sql`${t.owaspCategory} IS NULL OR length(${t.owaspCategory}) BETWEEN 1 AND 120`,
    ),
    check(
      'findings_severity_check',
      sql`${t.severity} IS NULL OR (jsonb_typeof(${t.severity}) = 'object' AND octet_length(${t.severity}::text) <= ${sql.raw(String(FINDING_SEVERITY_MAX_BYTES))})`,
    ),
    // A finding must be locatable: a URL template or a file (`findingLocationSchema`).
    check(
      'findings_location_check',
      sql`jsonb_typeof(${t.location}) = 'object' AND (${t.location}->>'urlTemplate' IS NOT NULL OR ${t.location}->>'file' IS NOT NULL) AND octet_length(${t.location}::text) <= ${sql.raw(String(FINDING_LOCATION_MAX_BYTES))}`,
    ),
    check('findings_status_check', sql`${t.status} IN (${inList(findingStatusSchema.options)})`),
    check(
      'findings_baseline_status_check',
      sql`${t.baselineStatus} IS NULL OR ${t.baselineStatus} IN (${inList(baselineStatusSchema.options)})`,
    ),
    check(
      'findings_confidence_check',
      sql`${t.confidence} IS NULL OR (${t.confidence} >= 0 AND ${t.confidence} <= 1)`,
    ),
    // A released, fixed or returned finding records who released it and when.
    check(
      'findings_released_check',
      sql`${t.status} NOT IN (${inList(RELEASED_STATUSES)}) OR (${t.releasedBy} IS NOT NULL AND ${t.releasedAt} IS NOT NULL)`,
    ),
    // accepted_risk is set exactly when the status is accepted_risk (§3.4: reason and expiry).
    check(
      'findings_accepted_risk_check',
      sql`(${t.status} = 'accepted_risk') = (${t.acceptedRisk} IS NOT NULL)`,
    ),
    check(
      'findings_accepted_risk_object_check',
      sql`${t.acceptedRisk} IS NULL OR jsonb_typeof(${t.acceptedRisk}) = 'object'`,
    ),
    check('findings_state_version_check', sql`${t.stateVersion} >= 0`),
    check(
      'findings_narrative_check',
      sql`(${t.description} IS NULL OR length(${t.description}) BETWEEN 1 AND ${sql.raw(String(FINDING_NARRATIVE_MAX_CHARS))})
        AND (${t.impact} IS NULL OR length(${t.impact}) BETWEEN 1 AND ${sql.raw(String(FINDING_NARRATIVE_MAX_CHARS))})
        AND (${t.evidenceNarrative} IS NULL OR length(${t.evidenceNarrative}) BETWEEN 1 AND ${sql.raw(String(FINDING_NARRATIVE_MAX_CHARS))})
        AND (${t.severityRationale} IS NULL OR length(${t.severityRationale}) BETWEEN 1 AND ${sql.raw(String(FINDING_NARRATIVE_MAX_CHARS))})
        AND (${t.remediationSummary} IS NULL OR length(${t.remediationSummary}) BETWEEN 1 AND ${sql.raw(String(FINDING_NARRATIVE_MAX_CHARS))})`,
    ),
    check(
      'findings_asvs_refs_check',
      sql`${t.asvsRefs} IS NULL OR (jsonb_typeof(${t.asvsRefs}) = 'array' AND jsonb_array_length(${t.asvsRefs}) <= 32 AND octet_length(${t.asvsRefs}::text) <= 4096)`,
    ),
    pgPolicy('findings_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);

/** One run's sighting of a finding (FINDING-001). Written once per (finding, run). */
export const findingOccurrences = pgTable(
  'finding_occurrences',
  {
    id: idColumn(),
    tenantId: tenantIdColumn(),
    findingId: uuid('finding_id').notNull(),
    runId: uuid('run_id').notNull(),
    /** What the run observed for this finding. The vocabulary is owned by the validator and retest flows. */
    occurrenceStatus: text('occurrence_status').notNull(),
    /** Head hash of the evidence chain at detection time (SHA-256 hex), or null. */
    evidenceChainHead: text('evidence_chain_head'),
    /** The bound evidence chain, in order (EVIDENCE, #724): references only, never bytes. Empty until bound. */
    evidenceRefs: jsonb('evidence_refs')
      .$type<EvidenceChainRef[]>()
      .notNull()
      .default(sql`'[]'::jsonb`),
    detectedAt: timestamp('detected_at', { withTimezone: true, mode: 'date' }).notNull(),
    ...timestamps(),
  },
  (t): PgTableExtraConfigValue[] => [
    tenantIdIndex('finding_occurrences', t.tenantId),
    // One occurrence per finding and run, and the (finding_id, run_id) lookup index.
    uniqueIndex('finding_occurrences_finding_id_run_id_key').on(t.findingId, t.runId),
    // Composite FK: plain FK checks bypass RLS, so a single-column reference could cross tenants.
    foreignKey({
      name: 'finding_occurrences_finding_fk',
      columns: [t.tenantId, t.findingId],
      foreignColumns: [findings.tenantId, findings.id],
    }),
    check('finding_occurrences_status_check', sql`length(${t.occurrenceStatus}) BETWEEN 1 AND 120`),
    check(
      'finding_occurrences_evidence_refs_check',
      sql`jsonb_typeof(${t.evidenceRefs}) = 'array' AND octet_length(${t.evidenceRefs}::text) <= 8192`,
    ),
    check(
      'finding_occurrences_evidence_chain_head_check',
      sql`${t.evidenceChainHead} IS NULL OR ${t.evidenceChainHead} ~ '^[0-9a-f]{64}$'`,
    ),
    pgPolicy('finding_occurrences_tenant_isolation', {
      as: 'permissive',
      for: 'all',
      to: 'public',
      using: TENANT_PREDICATE,
      withCheck: TENANT_PREDICATE,
    }),
  ],
);
