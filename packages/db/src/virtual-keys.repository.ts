// Tenant-scoped persistence of per-session virtual model keys (GATEWAY-002, #405, CONTEXT_PACK §7, §8.6, §8.8).
// Writes and tenant reads run through `withTenant`, so RLS confines them and a missing tenant fails closed.
// `resolve` is the one cross-tenant read: the gateway meets a key before it knows the tenant, so it looks the
// row up by the key's SHA-256 under `withSystem` (audited, §8.8). The transaction sets `app.tenant_id` to the
// nil UUID, which matches no tenant row, and `app.virtual_key_sha256` to the presented hash, which the
// `virtual_keys_resolve_by_hash` policy matches. A key can therefore only ever resolve to its own row.

import { and, eq, inArray, isNull, sql } from 'drizzle-orm';

import { authenticateVirtualKey, type VirtualKeyRecord } from '@blackwing/domain';

import {
  virtualKeys,
  VIRTUAL_KEY_RESOLVE_SETTING,
  type VirtualKeyRow,
} from './schema/virtual-keys.js';
import { withSystem, withTenant, type SystemAuditEmitter, type TenantTx } from './with-tenant.js';

import type { Database } from './client.js';
import type { VirtualKeyContext } from '@blackwing/contracts';

/** The tenant id no real row carries (UUIDv7 never yields it), used so the tenant policy matches nothing. */
const NIL_TENANT_ID = '00000000-0000-0000-0000-000000000000';

/** A key row as the repository hands it out. Never contains the raw key. */
export interface StoredVirtualKey {
  readonly id: string;
  readonly tenantId: string;
  readonly runId: string;
  readonly sessionId: string;
  readonly keyPrefix: string;
  readonly persona: string;
  readonly scope: Readonly<Record<string, unknown>>;
  readonly budgetContext: Readonly<Record<string, unknown>>;
  readonly expiresAt: Date;
  readonly revokedAt: Date | null;
  readonly lastUsedAt: Date | null;
}

/** What `mint` persists: the id is generated by the caller, the hash is computed from the key it returned. */
export interface NewVirtualKey {
  readonly id: string;
  readonly tenantId: string;
  readonly runId: string;
  readonly sessionId: string;
  readonly keyPrefix: string;
  readonly keySha256: Buffer;
  readonly persona: string;
  readonly scope: Readonly<Record<string, unknown>>;
  readonly budgetContext: Readonly<Record<string, unknown>>;
  readonly expiresAt: Date;
}

interface ResolveOptions {
  readonly audit: SystemAuditEmitter;
  readonly actor: string;
  readonly reason: string;
}

/**
 * Persists virtual keys. `afterWrite` runs in the same transaction as the write, so the audit event of a
 * mint or revoke commits together with it or not at all (§8.8).
 */
export interface VirtualKeyStore {
  mint(row: NewVirtualKey, afterWrite: (tx: TenantTx) => Promise<void>): Promise<StoredVirtualKey>;
  resolve(keySha256: Buffer, options: ResolveOptions): Promise<StoredVirtualKey | null>;
  markUsed(tenantId: string, id: string): Promise<void>;
  revokeIds(
    tenantId: string,
    ids: readonly string[],
    afterWrite: (tx: TenantTx, revokedIds: readonly string[]) => Promise<void>,
  ): Promise<string[]>;
  revokeRun(
    tenantId: string,
    runId: string,
    afterWrite: (tx: TenantTx, revokedIds: readonly string[]) => Promise<void>,
  ): Promise<string[]>;
}

function toStoredVirtualKey(row: VirtualKeyRow): StoredVirtualKey {
  return {
    id: row.id,
    tenantId: row.tenantId,
    runId: row.runId,
    sessionId: row.sessionId,
    keyPrefix: row.keyPrefix,
    persona: row.persona,
    scope: row.scope,
    budgetContext: row.budgetContext,
    expiresAt: row.expiresAt,
    revokedAt: row.revokedAt,
    lastUsedAt: row.lastUsedAt,
  };
}

/** Builds the Postgres-backed store over the app pool. */
export function createPgVirtualKeyStore(db: Database): VirtualKeyStore {
  return {
    async mint(row, afterWrite) {
      return withTenant(db, row.tenantId, async (tx) => {
        const [inserted] = await tx
          .insert(virtualKeys)
          .values({
            id: row.id,
            tenantId: row.tenantId,
            runId: row.runId,
            sessionId: row.sessionId,
            keyPrefix: row.keyPrefix,
            keySha256: row.keySha256,
            persona: row.persona,
            scope: { ...row.scope },
            budgetContext: { ...row.budgetContext },
            expiresAt: row.expiresAt,
          })
          .returning();
        if (inserted === undefined) throw new Error('virtual key insert returned no row');
        await afterWrite(tx);
        return toStoredVirtualKey(inserted);
      });
    },

    async resolve(keySha256, options) {
      return withSystem(
        db,
        async (tx) => {
          await tx.execute(
            sql`SELECT set_config('app.tenant_id', ${NIL_TENANT_ID}, true), set_config(${VIRTUAL_KEY_RESOLVE_SETTING}, ${keySha256.toString('hex')}, true)`,
          );
          const [row] = await tx
            .select()
            .from(virtualKeys)
            .where(eq(virtualKeys.keySha256, keySha256))
            .limit(1);
          return row === undefined ? null : toStoredVirtualKey(row);
        },
        options,
      );
    },

    async markUsed(tenantId, id) {
      await withTenant(db, tenantId, async (tx) => {
        await tx
          .update(virtualKeys)
          .set({ lastUsedAt: sql`now()` })
          .where(and(eq(virtualKeys.tenantId, tenantId), eq(virtualKeys.id, id)));
      });
    },

    async revokeIds(tenantId, ids, afterWrite) {
      if (ids.length === 0) return [];
      return withTenant(db, tenantId, async (tx) => {
        const revoked = await tx
          .update(virtualKeys)
          .set({ revokedAt: sql`now()` })
          .where(
            and(
              eq(virtualKeys.tenantId, tenantId),
              inArray(virtualKeys.id, [...ids]),
              isNull(virtualKeys.revokedAt),
            ),
          )
          .returning({ id: virtualKeys.id });
        const revokedIds = revoked.map((row) => row.id);
        await afterWrite(tx, revokedIds);
        return revokedIds;
      });
    },

    async revokeRun(tenantId, runId, afterWrite) {
      return withTenant(db, tenantId, async (tx) => {
        const revoked = await tx
          .update(virtualKeys)
          .set({ revokedAt: sql`now()` })
          .where(
            and(
              eq(virtualKeys.tenantId, tenantId),
              eq(virtualKeys.runId, runId),
              isNull(virtualKeys.revokedAt),
            ),
          )
          .returning({ id: virtualKeys.id });
        const revokedIds = revoked.map((row) => row.id);
        await afterWrite(tx, revokedIds);
        return revokedIds;
      });
    },
  };
}

export interface VirtualKeyAuthenticatorOptions {
  readonly store: VirtualKeyStore;
  /** Audit of the tenant-less resolve (`db.system_access`, §8.8). */
  readonly audit: SystemAuditEmitter;
  /** Actor recorded on the resolve audit event, e.g. `model-gateway`. */
  readonly actor: string;
  readonly now?: () => Date;
}

/**
 * Authenticates a presented `bwk_` key: resolves its row by hash (audited), applies the domain's expiry and
 * revocation rules, and stamps `last_used_at` on success. Every refusal is `undefined`, so callers answer one
 * uniform 401. A database error rejects, which callers must treat as a refusal (fail closed).
 */
export function createVirtualKeyAuthenticator(
  options: VirtualKeyAuthenticatorOptions,
): (key: string) => Promise<VirtualKeyContext | undefined> {
  const { store } = options;
  const now = options.now ?? (() => new Date());
  return async (key) => {
    const context = await authenticateVirtualKey(
      key,
      async (keySha256) => {
        const row = await store.resolve(keySha256, {
          audit: options.audit,
          actor: options.actor,
          reason: 'virtual key resolution',
        });
        if (row === null) return null;
        const record: VirtualKeyRecord = {
          id: row.id,
          tenantId: row.tenantId,
          runId: row.runId,
          sessionId: row.sessionId,
          persona: row.persona,
          budgetContext: row.budgetContext,
          expiresAt: row.expiresAt,
          revokedAt: row.revokedAt,
        };
        return record;
      },
      now(),
    );
    if (context !== undefined) await store.markUsed(context.tenantId, context.virtualKeyId);
    return context;
  };
}
