// The migration runner (DB-002, CONTEXT_PACK §5, §7). Applies the committed, reviewed SQL migrations
// in journal order, as the owner role, in ONE transaction under an advisory lock, and records each
// applied version in drizzle.__drizzle_migrations (the same table and format drizzle-kit uses, so the
// two stay interchangeable). Forward-only in production: see ./migrate-guard.ts.

import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { readMigrationFiles } from 'drizzle-orm/migrator';
import { z } from 'zod';

import { assertMigrationAllowed, type MigrationGuardEnv } from './migrate-guard.js';

import type pg from 'pg';

/** Absolute path of the forward-only SQL migrations (generated by `pnpm db:generate`, then reviewed). */
export const MIGRATIONS_DIR = fileURLToPath(new URL('../migrations/', import.meta.url));

/** Dev-only down migrations, `<tag>.sql`, refused in production without the explicit flag. */
export const DOWN_MIGRATIONS_DIR = `${MIGRATIONS_DIR}down/`;

/** Where applied migrations are recorded (same as `src/drizzle.config.ts`). */
export const MIGRATIONS_TABLE = Object.freeze({ schema: 'drizzle', table: '__drizzle_migrations' });

/** Serialises concurrent migrate jobs (two deploys racing) on one database. */
const MIGRATION_LOCK_KEY = 'blackwing:db:migrate';

/** The structured-logger surface the migrator needs (satisfied by `@blackwing/logger`). */
export interface MigrationLogger {
  info(fields: Record<string, unknown>, message: string): void;
}

const journalSchema = z.object({
  entries: z.array(
    z.object({ idx: z.int().nonnegative(), tag: z.string().min(1), when: z.number() }),
  ),
});

/** One committed migration, in apply order. */
export interface MigrationEntry {
  /** The journal tag, e.g. `0001_kill_switch` (also the file name without `.sql`). */
  readonly version: string;
  /** The journal timestamp, recorded as `created_at`; a migration applies when it is newer than the last one. */
  readonly folderMillis: number;
  /** sha256 of the SQL file, recorded as `hash`. */
  readonly hash: string;
  /** The statements, split on drizzle's `--> statement-breakpoint`. */
  readonly statements: readonly string[];
}

/** Loads the committed migrations from `dir` (default {@link MIGRATIONS_DIR}) in journal order. */
export function loadMigrations(dir: string = MIGRATIONS_DIR): MigrationEntry[] {
  const raw: unknown = JSON.parse(readFileSync(`${dir}/meta/_journal.json`, 'utf8'));
  const entries = journalSchema.parse(raw).entries;
  const files = readMigrationFiles({ migrationsFolder: dir });
  return entries.map((entry, index) => {
    const file = files[index];
    if (file === undefined) throw new Error(`migration ${entry.tag} is missing`);
    return {
      version: entry.tag,
      folderMillis: file.folderMillis,
      hash: file.hash,
      statements: file.sql,
    };
  });
}

/** The migration names in apply order, e.g. `0001_kill_switch`, from the drizzle journal. */
export function migrationNames(dir: string = MIGRATIONS_DIR): string[] {
  return loadMigrations(dir).map((entry) => entry.version);
}

/** Options for {@link migrateDatabase}. */
export interface MigrateOptions {
  /** Migrations directory (default {@link MIGRATIONS_DIR}); tests point it at fixtures. */
  readonly migrationsDir?: string;
  /** The guard's environment (`NODE_ENV`, `ALLOW_DESTRUCTIVE_MIGRATION`); default: not production. */
  readonly env?: MigrationGuardEnv;
  /** Monotonic clock for durations (default `performance.now`). */
  readonly now?: () => number;
}

/** What one run did. */
export interface MigrationResult {
  readonly applied: readonly string[];
  readonly skipped: readonly string[];
}

const qualifiedTable = `"${MIGRATIONS_TABLE.schema}"."${MIGRATIONS_TABLE.table}"`;

async function lastAppliedMillis(client: pg.ClientBase): Promise<number | undefined> {
  const { rows } = await client.query<{ created_at: string | null }>(
    `SELECT created_at FROM ${qualifiedTable} ORDER BY created_at DESC LIMIT 1`,
  );
  const value = rows[0]?.created_at;
  return value === undefined || value === null ? undefined : Number(value);
}

/**
 * Applies every pending migration. Call it with a client connected as the owner role (`bw_owner`):
 * migrations never run as the RLS-subject app role, which lacks the privileges and fails (§7, §8.6).
 *
 * All pending migrations run in one transaction (Postgres DDL is transactional), so a crash leaves
 * the database at the previous version; the statements that cannot be transactional are kept
 * idempotent (`IF NOT EXISTS`) and are enforced by `pnpm db:check`. The production guard runs on
 * every pending migration before anything is applied. Logs versions and durations only.
 */
export async function migrateDatabase(
  client: pg.ClientBase,
  logger?: MigrationLogger,
  options: MigrateOptions = {},
): Promise<MigrationResult> {
  const now = options.now ?? (() => performance.now());
  const migrations = loadMigrations(options.migrationsDir);
  const env = options.env ?? {};
  const startedAt = now();

  await client.query(`CREATE SCHEMA IF NOT EXISTS "${MIGRATIONS_TABLE.schema}"`);
  await client.query(
    `CREATE TABLE IF NOT EXISTS ${qualifiedTable} (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint)`,
  );

  await client.query('BEGIN');
  try {
    await client.query('SELECT pg_advisory_xact_lock(hashtext($1))', [MIGRATION_LOCK_KEY]);
    const last = await lastAppliedMillis(client);
    const pending = migrations.filter((m) => last === undefined || m.folderMillis > last);
    const skipped = migrations.filter((m) => !pending.includes(m)).map((m) => m.version);
    logger?.info(
      { event: 'db.migrate.start', total: migrations.length, pending: pending.length },
      'db.migrate.start',
    );
    for (const migration of pending) {
      assertMigrationAllowed(
        { version: migration.version, direction: 'up', sql: migration.statements.join('\n') },
        env,
      );
    }
    for (const version of skipped) {
      logger?.info({ event: 'db.migrate.skipped', version }, 'db.migrate.skipped');
    }
    for (const migration of pending) {
      const began = now();
      for (const statement of migration.statements) {
        await client.query(statement);
      }
      await client.query(`INSERT INTO ${qualifiedTable} (hash, created_at) VALUES ($1, $2)`, [
        migration.hash,
        migration.folderMillis,
      ]);
      logger?.info(
        {
          event: 'db.migrate.applied',
          version: migration.version,
          durationMs: Math.round(now() - began),
        },
        'db.migrate.applied',
      );
    }
    await client.query('COMMIT');
    const applied = pending.map((m) => m.version);
    logger?.info(
      {
        event: 'db.migrate.done',
        applied: applied.length,
        skipped: skipped.length,
        durationMs: Math.round(now() - startedAt),
      },
      'db.migrate.done',
    );
    return { applied, skipped };
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw error;
  }
}

/**
 * Reverts the latest applied migration with its dev-only `migrations/down/<tag>.sql` and removes its
 * record. Refused in production unless `ALLOW_DESTRUCTIVE_MIGRATION=1` (forward-only). Returns the
 * reverted version, or `undefined` when nothing is applied.
 */
export async function rollbackLatestMigration(
  client: pg.ClientBase,
  logger?: MigrationLogger,
  options: MigrateOptions = {},
): Promise<string | undefined> {
  const dir = options.migrationsDir ?? MIGRATIONS_DIR;
  const migrations = loadMigrations(dir);
  await client.query('BEGIN');
  try {
    await client.query('SELECT pg_advisory_xact_lock(hashtext($1))', [MIGRATION_LOCK_KEY]);
    const last = await lastAppliedMillis(client);
    const latest = migrations.findLast((m) => last !== undefined && m.folderMillis <= last);
    if (latest === undefined) {
      await client.query('ROLLBACK');
      return undefined;
    }
    const downFile = `${dir}/down/${latest.version}.sql`;
    if (!existsSync(downFile)) {
      throw new Error(`migration ${latest.version} has no down migration (${downFile})`);
    }
    const sql = readFileSync(downFile, 'utf8');
    assertMigrationAllowed({ version: latest.version, direction: 'down', sql }, options.env ?? {});
    await client.query(sql);
    await client.query(`DELETE FROM ${qualifiedTable} WHERE created_at = $1`, [
      latest.folderMillis,
    ]);
    await client.query('COMMIT');
    logger?.info({ event: 'db.migrate.reverted', version: latest.version }, 'db.migrate.reverted');
    return latest.version;
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw error;
  }
}
