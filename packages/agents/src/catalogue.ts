import { resolveTier } from './tier.js';

import type { PersonaDefinition } from './persona.js';

/**
 * The persona catalogue (REGISTRY-011, CONTEXT_PACK §4.6). A human-readable page that says what every persona
 * may do. It is derived from the definitions, never hand-maintained: `pnpm gen:persona-catalogue` writes it and
 * the drift check fails when the committed file is stale.
 */

/** The generated page, relative to the repository root. */
export const PERSONA_CATALOGUE_PATH = 'docs/architecture/persona-catalogue.md';

const NONE = '_none_';

/** Inline code for a list of identifiers, or `none` when the list is empty. */
function codeList(values: readonly string[]): string {
  return values.length === 0 ? NONE : values.map((v) => `\`${v}\``).join(', ');
}

/** One persona as a section: the mandate and every setting a run pins from the definition. */
function renderPersona(def: PersonaDefinition): string {
  const model = resolveTier(def.tierAlias, 'anthropic');
  const helpers =
    def.helpers === undefined || def.helpers.length === 0
      ? NONE
      : def.helpers
          .map(
            (h) =>
              `\`${h.name}\` (tier \`${h.tierAlias}\`, tools ${codeList(h.allowedTools)}): ${h.description}`,
          )
          .join('; ');
  return [
    `## \`${def.name}\``,
    '',
    `- **Mandate:** ${def.mandate}`,
    `- **Model tier:** \`${def.tierAlias}\` → \`${model}\` (Anthropic provider; Bedrock adds the \`anthropic.\` prefix)`,
    `- **Effort:** \`${def.effort}\`; **max turns:** ${String(def.maxTurns)}; **default budget:** $${String(def.maxBudgetUsdDefault)}`,
    `- **Intrusiveness ceiling:** \`${def.intrusivenessCeiling}\`; **submission required:** ${def.requiresSubmission ? 'yes' : 'no'}`,
    `- **Prompt version:** \`${def.promptRef.version}\``,
    `- **Allowed tools:** ${codeList(def.allowedTools)}`,
    `- **Disallowed tools:** ${codeList(def.disallowedTools)}`,
    `- **Declared oracle types:** ${codeList(def.declaredOracleTypes)}`,
    `- **Inputs:** ${codeList(def.inputs)}`,
    `- **Helpers:** ${helpers}`,
    '',
  ].join('\n');
}

/**
 * Renders the catalogue page for `definitions`, in the order given. The output is deterministic (no clock, no
 * environment), so the same definitions always produce the same bytes.
 */
export function renderPersonaCatalogue(definitions: readonly PersonaDefinition[]): string {
  const header = [
    '# Persona catalogue',
    '',
    '<!-- Generated by `pnpm gen:persona-catalogue` from packages/agents. Do not edit by hand. -->',
    '',
    'What each agent persona may do. The definitions in `packages/agents/src/personas` are the source; this page is',
    'regenerated from them and CI fails when it is stale. Tenant overrides (effort, turns, budget and standard-tier',
    'lowering) change the effective values of one tenant only; see `GET /v1/personas` for those.',
    '',
  ].join('\n');
  const sections = definitions.map((def) => renderPersona(def)).join('\n');
  return `${header}\n${sections}`;
}
