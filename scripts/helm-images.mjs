#!/usr/bin/env node
// Renders the image hand-off values of the Blackwing umbrella chart (#44). It reads CI-007's images.json
// (service -> ghcr.io/tinycrowslab/bw-<service>@sha256:...) and IMAGE-012's surfaced sandbox digest
// (infra/docker/sandbox/IMAGE_DIGEST), and writes a Helm values file with global.images and
// global.sandbox.imageRef. It fails on a missing, tag-only or malformed entry, and never falls back
// to a tag, so a deploy cannot start from an unpinned image.
//
// Usage: node scripts/helm-images.mjs --images-json <file> --out <file> [--sandbox-digest <file>]

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { stringify } from 'yaml';

import { REGISTRY } from './check-images.mjs';

/** The long-running services the umbrella chart deploys (bw-sandbox is spawned at runtime, not deployed). */
export const CHART_APPS = Object.freeze([
  'web',
  'api',
  'worker',
  'model-gateway',
  'egress-gateway',
  'session-manager',
  'sandbox-controller',
]);

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_SANDBOX_DIGEST = path.join(REPO, 'infra', 'docker', 'sandbox', 'IMAGE_DIGEST');

/**
 * The only accepted form of a hand-off reference: the canonical registry, the image of that service,
 * and a sha256 digest. A tag, another registry or another image name is refused.
 * @param {string} service
 * @returns {RegExp}
 */
function referencePattern(service) {
  const prefix = `${REGISTRY}/bw-${service}`.replaceAll('.', '\\.');
  return new RegExp(`^${prefix}@sha256:[0-9a-f]{64}$`);
}

/**
 * Builds the values object from the two hand-off inputs.
 * @param {unknown} imagesJson parsed CI-007 images.json (service -> pinned reference)
 * @param {string} sandboxDigest contents of IMAGE_DIGEST (surrounding whitespace is allowed)
 * @returns {{ global: { images: Record<string, string>, sandbox: { imageRef: string } } }}
 */
export function buildImageValues(imagesJson, sandboxDigest) {
  if (imagesJson === null || typeof imagesJson !== 'object' || Array.isArray(imagesJson)) {
    throw new Error('images.json must be a JSON object (service -> pinned reference)');
  }
  const entries = /** @type {Record<string, unknown>} */ (imagesJson);
  for (const [service, ref] of Object.entries(entries)) {
    if (typeof ref !== 'string' || !referencePattern(service).test(ref)) {
      throw new Error(
        `images.json: ${service} is not a digest-pinned ${REGISTRY}/bw-${service} reference`,
      );
    }
  }
  /** @type {Record<string, string>} */
  const images = {};
  for (const app of CHART_APPS) {
    const ref = entries[app];
    if (typeof ref !== 'string') throw new Error(`images.json has no entry for ${app}`);
    images[app] = ref;
  }
  const sandbox = sandboxDigest.trim();
  if (!referencePattern('sandbox').test(sandbox)) {
    throw new Error(
      `IMAGE_DIGEST must hold a digest-pinned ${REGISTRY}/bw-sandbox reference (got ${sandbox === '' ? 'an empty file' : 'a malformed value'})`,
    );
  }
  return { global: { images, sandbox: { imageRef: sandbox } } };
}

/** @param {string[]} argv @returns {number} exit code */
function main(argv) {
  const arg = (/** @type {string} */ name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const imagesJson = arg('--images-json');
  const out = arg('--out');
  const sandboxDigest = arg('--sandbox-digest') ?? DEFAULT_SANDBOX_DIGEST;
  if (imagesJson === undefined || out === undefined) {
    process.stderr.write(
      'usage: helm-images --images-json <file> --out <file> [--sandbox-digest <file>]\n',
    );
    return 2;
  }
  try {
    const values = buildImageValues(
      JSON.parse(readFileSync(imagesJson, 'utf8')),
      readFileSync(sandboxDigest, 'utf8'),
    );
    const header =
      '# Generated by scripts/helm-images.mjs from CI-007 images.json and IMAGE-012 IMAGE_DIGEST. Do not edit.\n';
    writeFileSync(out, `${header}${stringify(values)}`);
    return 0;
  } catch (e) {
    process.stderr.write(`helm-images: ${e instanceof Error ? e.message : String(e)}\n`);
    return 1;
  }
}

if (
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = main(process.argv.slice(2));
}
